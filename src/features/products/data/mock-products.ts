// Pre-computed lookup index maps
const PRODUCT_BY_ID = new Map<string, Product>(
  MOCK_PRODUCTS.map((p) => [p.id, p]),
);

const PRODUCT_BY_SLUG = new Map<string, Product>(
  MOCK_PRODUCTS.map((p) => [p.slug, p]),
);

/**
 * Returns all mock products in the catalog.
 */
export function getMockProducts(): readonly Product[] {
  return MOCK_PRODUCTS;
}

/**
 * Finds a mock product by its unique entity ID.
 */
export function getMockProductById(id: string): Product | undefined {
  if (!id) return undefined;
  return PRODUCT_BY_ID.get(id);
}

/**
 * Finds a mock product by its URL-safe slug.
 */
export function getMockProductBySlug(slug: string): Product | undefined {
  if (!slug) return undefined;
  return PRODUCT_BY_SLUG.get(slug.toLowerCase().trim());
}

/**
 * Returns mock products belonging to a specific category slug.
 */
export function getMockProductsByCategory(categorySlug: string): readonly Product[] {
  if (!categorySlug) return [];
  const normalized = categorySlug.toLowerCase().trim();
  return MOCK_PRODUCTS.filter((p) => p.categorySlug === normalized);
}

/**
 * Returns mock products belonging to a specific subcategory slug.
 */
export function getMockProductsBySubcategory(subcategorySlug: string): readonly Product[] {
  if (!subcategorySlug) return [];
  const normalized = subcategorySlug.toLowerCase().trim();
  return MOCK_PRODUCTS.filter((p) => p.subcategorySlug === normalized);
}

/**
 * Returns featured mock products for homepage showcases.
 */
export function getFeaturedMockProducts(): readonly Product[] {
  return MOCK_PRODUCTS.filter((p) => p.isFeatured);
}
